# functions = block of reuseable code
#             place "()" after the function name to invoke it 
def happy_birthday(name,age):
    print(f"happy birthday {name}")
    print(f"u r {age} years old")
    
happy_birthday("raj",27)
happy_birthday("jay",28)

# op => happy birthday raj
# u r 27 years old
# happy birthday jay
# u r 28 years old

